CREATE TABLE eleve (
    id_eleve BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    telephone VARCHAR(255),
    date_inscription DATE NOT NULL
);

CREATE TABLE moniteur (
    id_moniteur BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    telephone VARCHAR(255),
    actif BOOLEAN NOT NULL
);

CREATE TABLE vehicule (
    id_vehicule BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    immatriculation VARCHAR(255) NOT NULL UNIQUE,
    marque VARCHAR(255) NOT NULL,
    modele VARCHAR(255) NOT NULL,
    etat VARCHAR(255) NOT NULL
);

CREATE TABLE examen (
    id_examen BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_examen VARCHAR(255) NOT NULL,
    date_examen DATE NOT NULL,
    lieu VARCHAR(255) NOT NULL
);

CREATE TABLE auth_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    account_role VARCHAR(16) NOT NULL,
    id_eleve BIGINT UNIQUE REFERENCES eleve (id_eleve),
    verified BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE auth_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES auth_account (id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE email_verification_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL UNIQUE REFERENCES auth_account (id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE seance_conduite (
    id_seance BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_seance DATE NOT NULL,
    heure_debut TIME NOT NULL,
    duree INTEGER NOT NULL,
    statut VARCHAR(255) NOT NULL,
    id_eleve BIGINT NOT NULL REFERENCES eleve (id_eleve),
    id_moniteur BIGINT NOT NULL REFERENCES moniteur (id_moniteur),
    id_vehicule BIGINT NOT NULL REFERENCES vehicule (id_vehicule)
);

CREATE TABLE resultat_examen (
    id_resultat BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_eleve BIGINT NOT NULL REFERENCES eleve (id_eleve),
    id_examen BIGINT NOT NULL REFERENCES examen (id_examen),
    note NUMERIC(38, 2),
    resultat VARCHAR(255) NOT NULL
);
